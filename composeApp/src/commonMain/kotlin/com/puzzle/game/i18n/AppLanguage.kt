    fun pieceLabel(count: Int): String = when (this) {
        EnglishStrings -> if (count == 1) "$count piece" else "$count pieces"
        JapaneseStrings -> "${count}ピース"
        TraditionalChineseStrings -> "${count}片"
        else -> "${count}片"
    }

    fun actLabel(count: Int): String = when (this) {
        EnglishStrings -> if (count == 1) "$count scene" else "$count scenes"
        JapaneseStrings -> "全${count}幕"
        TraditionalChineseStrings -> "${count}幕"
        else -> "${count}幕"
    }

    fun progress(placed: Int, total: Int): String = placedProgress
        .replace("{placed}", placed.toString())
        .replace("{total}", total.toString())

    fun completionMessage(pieceCount: Int): String = completedMessage
        .replace("{count}", pieceCount.toString())
}

